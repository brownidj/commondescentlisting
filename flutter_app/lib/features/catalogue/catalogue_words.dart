final _wordPattern = RegExp(
  r"[\p{L}\p{N}]+(?:['’\-][\p{L}\p{N}]+)*",
  unicode: true,
);

Iterable<String> _words(String value) => _wordPattern
    .allMatches(value.toLowerCase())
    .map((match) => match.group(0)!);

bool isFunctionOnlyPhrase(String value) {
  final words = _words(value).toList();
  return words.isEmpty || words.every(catalogueFunctionWords.contains);
}

/// File titles by the first meaningful word, retaining a stable key for titles
/// made entirely of grammatical words. Source titles remain unchanged.
String episodeTitleSortKey(String title) {
  final words = _words(title).toList();
  final filed = words.skipWhile(catalogueFunctionWords.contains).join(' ');
  return filed.isEmpty ? words.join(' ') : filed;
}
